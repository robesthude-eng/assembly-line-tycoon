package com.example.assemblylinetycoon.domain.model


/**
 * Накопительная статистика производства.
 *
 * Нужна не только для экрана статистики: [coinsPerSecond] — это то, по чему
 * считается офлайн-доход, поэтому цифра должна браться из реальной работы
 * завода, а не из отдельной оценки «на глазок».
 *
 * Счётчики только растут и никогда не обнуляются в ходе сессии, поэтому
 * подходят для достижений и защищены от переполнения ёмкостью [Long].
 */
data class ProductionStats(
    /** Сколько предметов машины выпустили за всё время. */
    val itemsProduced: Long = 0L,

    /** Сколько предметов ушло через экспортёр. */
    val itemsExported: Long = 0L,

    /** Сколько монет принёс экспорт за всё время. */
    val coinsEarned: Long = 0L,

    /** Сколько игрового времени отработала симуляция, мс. */
    val simulatedMillis: Long = 0L,
) {
    /**
     * Средний доход в секунду за всё отработанное время.
     *
     * Средняя, а не мгновенная величина: мгновенная скачет от такта к такту
     * (экспорт происходит редкими порциями), и офлайн-доход по ней получался
     * бы случайным — в зависимости от того, в какой момент игрок вышел.
     */
    val coinsPerSecond: Double
        get() = if (simulatedMillis <= 0L) 0.0 else coinsEarned.toDouble() / (simulatedMillis / 1000.0)

    companion object {
        val EMPTY = ProductionStats()
    }
}
